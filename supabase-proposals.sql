-- Designed proposals (the pages built with the generator). Added 24.11.2026.
-- Run once in the Supabase SQL editor.
--
-- RLS is ON with no policies on purpose: the browser (anon key) cannot read or write this table.
-- Only the server routes under app/api/proposals and app/p use it, with the service role key.
-- The existing `quotes` table (the simple QuoteBuilder proposals) is not touched.

create table if not exists proposals (
  id text primary key,
  lead_id text default '',
  org_name text default '',
  label text default '',
  token text not null unique,          -- the unguessable part of the public link /p/<token>
  html text not null,                  -- the finished page (both languages), generated by bilingual_page.py
  status text default 'draft',         -- draft | sent | viewed | signed
  created_at timestamptz default now(),
  sent_at timestamptz,
  first_viewed_at timestamptz,
  last_viewed_at timestamptz,
  view_count integer default 0,
  signed_at timestamptz,
  signed_name text,
  signed_role text,
  signed_lang text,
  signature text,                      -- png data url of the drawn signature
  signed_ip text,
  signed_ua text,
  signed_html_sha256 text              -- hash of the page as it was when signed
);

create index if not exists proposals_lead_idx on proposals (lead_id);

alter table proposals enable row level security;
