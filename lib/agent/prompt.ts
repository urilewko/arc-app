/** Builds the full system blocks, with the knowledge base marked for caching. */
export function buildSystem(
  knowledge: string,
  liveContext?: string,
  memories?: string
) {
  const blocks: Array<{
    type: "text";
    text: string;
    cache_control?: { type: "ephemeral" };
  }> = [
    { type: "text", text: SYSTEM_PROMPT },
    {
      type: "text",
      text: `# בסיס הידע — כרטיסי הבלוקים\n\n${knowledge}`,
      // Stable across requests → cache it. Volatile context goes after.
      cache_control: { type: "ephemeral" },
    },
  ];

  // Memory and live rows change between turns, so they sit after the cache
  // breakpoint — putting them earlier would invalidate the knowledge base.
  if (memories) {
    blocks.push({
      type: "text",
      text: `# מה שלמדת עלינו עד היום\n\n${memories}`,
    });
  }

  if (liveContext) {
    blocks.push({
      type: "text",
      text: `# נתונים חיים מהמערכת\n\n${liveContext}`,
    });
  }

  return blocks;
}
